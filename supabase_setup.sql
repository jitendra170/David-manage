-- Create students table
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  name text not null,
  grade text,
  status text,
  admission_date date,
  roll_number text,
  grades jsonb,
  avg_grade numeric,
  created_at timestamptz default now()
);

-- Create teachers table
create table if not exists public.teachers (
  id bigint generated by default as identity primary key,
  name text not null,
  subject text,
  status text,
  email text,
  created_at timestamptz default now()
);

-- Create fees table
create table if not exists public.fees (
  id bigint generated by default as identity primary key,
  student_id bigint references public.students(id) on delete set null,
  student text,
  fee numeric,
  status text,
  created_at timestamptz default now()
);

-- Create attendance summary table (class-level)
create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  class_name text,
  present integer,
  attendance numeric,
  created_at timestamptz default now()
);

-- Create student_attendance table (per-student)
create table if not exists public.student_attendance (
  id bigint generated by default as identity primary key,
  student_id bigint references public.students(id) on delete set null,
  student text,
  class_name text,
  status text,
  date date,
  created_at timestamptz default now()
);

-- Create teacher_attendance table
create table if not exists public.teacher_attendance (
  id bigint generated by default as identity primary key,
  teacher_id bigint references public.teachers(id) on delete set null,
  teacher text,
  date date,
  status text,
  created_at timestamptz default now()
);

-- Optional: create simple indexes to speed common lookups
create index if not exists idx_students_roll on public.students (roll_number);
create index if not exists idx_teachers_email on public.teachers (email);
create index if not exists idx_fees_student on public.fees (student_id);

