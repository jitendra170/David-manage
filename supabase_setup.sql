-- Create the users table if it does not exist.
create table if not exists public.app_users (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text not null unique,
  password_hash text not null,
  role text not null check (lower(role) in ('teacher', 'principal', 'accountant', 'student', 'library')),
  created_at timestamptz default now()
);

alter table public.app_users
  drop constraint if exists app_users_role_check;

update public.app_users
set role = lower(trim(role))
where role is not null;

update public.app_users
set role = 'library'
where lower(trim(role)) = 'library staff';

update public.app_users
set role = 'student'
where lower(trim(role)) not in ('teacher', 'principal', 'accountant', 'student', 'library');

alter table public.app_users
  add constraint app_users_role_check
  check (lower(role) in ('teacher', 'principal', 'accountant', 'student', 'library'));

